static int copy6_from(uint8_t *dst, size_t dst_len, size_t dst_off,
                      const uint8_t *src, size_t src_len, size_t src_off) {
    if (!dst || !src || dst_off > dst_len || src_off > src_len ||
        6u > dst_len - dst_off || 6u > src_len - src_off) {
        return L3_PRIVATE_KEY_DISPATCH_ERR_ARGUMENT;
    }
    memcpy(dst + dst_off, src + src_off, 6u);
    return L3_PRIVATE_KEY_DISPATCH_OK;
}

static int param2_indexed_base(const uint8_t *param2, size_t param2_len, size_t *base) {
    if (!param2 || param2_len < 4u || !base) return L3_PRIVATE_KEY_DISPATCH_ERR_ARGUMENT;
    uint32_t n = (uint32_t)param2[0] |
                 ((uint32_t)param2[1] << 8) |
                 ((uint32_t)param2[2] << 16) |
                 ((uint32_t)param2[3] << 24);
    *base = (size_t)n * 6u;
    return L3_PRIVATE_KEY_DISPATCH_OK;
}


