#pragma once
#include "store.hpp"

extern std::string_view globalbasedir;
namespace juggluco::activity {
// Import, JNI and the web/file exporters must share both mappings and mutex.
inline Store &globalStore() {
    if(globalbasedir.empty())throw std::runtime_error("Juggluco data is not initialized");
    static Store store{std::string(globalbasedir)};
    return store;
}
}
