int aes_cfb128_decrypt(const unsigned char *ciphertext, int ciphertext_len, const unsigned char key[16], const unsigned char iv[16], unsigned char *plaintext) {
    const EVP_CIPHER *cipher{EVP_aes_128_cfb128()};
    EVP_CIPHER_CTX *ctx = EVP_CIPHER_CTX_new();
    if (!ctx) {
        LOGAR("EVP_CIPHER_CTX_new() failed");
        return -1;
        }
    destruct _{[ctx]{ EVP_CIPHER_CTX_free(ctx);}};

    int out_len1 = 0, out_len2 = 0;
    if(EVP_DecryptInit_ex(ctx, cipher, NULL, key, iv) != 1) {
        LOGAR("EVP_DecryptInit_ex failed");
        return -1;
        }
    if(EVP_DecryptUpdate(ctx, plaintext, &out_len1, ciphertext, ciphertext_len) != 1) {
        LOGAR("EVP_DecryptUpdate failed");
        return -2;
        }
    if(EVP_DecryptFinal_ex(ctx, plaintext + out_len1, &out_len2) != 1) {
        LOGAR("EVP_DecryptFinal_ex failed");
        return -3;
        }
    return out_len1 + out_len2;
    }
int aes_cfb128_encrypt(const unsigned char *plaintext, int plaintext_len, const unsigned char key[16], const unsigned char iv[16], unsigned char *ciphertext) {
    const EVP_CIPHER *cipher = EVP_aes_128_cfb128();
    EVP_CIPHER_CTX *ctx = EVP_CIPHER_CTX_new();
    if (!ctx) {
        LOGAR("EVP_CIPHER_CTX_new() failed");
        return -1;
    }
    destruct _{[ctx]{ EVP_CIPHER_CTX_free(ctx);}};

    int out_len1 = 0, out_len2 = 0;

    if (EVP_EncryptInit_ex(ctx, cipher, NULL, key, iv) != 1) {
        LOGAR("EVP_EncryptInit_ex failed");
        return -1;
    }

    if (EVP_EncryptUpdate(ctx, ciphertext, &out_len1, plaintext, plaintext_len) != 1) {
        LOGAR("EVP_EncryptUpdate failed");
        return -2;
    }

    /* In CFB mode this normally produces 0 bytes, but must still be called */
    if (EVP_EncryptFinal_ex(ctx, ciphertext + out_len1, &out_len2) != 1) {
        LOGAR("EVP_EncryptFinal_ex failed");
        return -3;
    }

    return out_len1 + out_len2;
}
