int aes_cfb128_decrypt(const unsigned char *ciphertext, int ciphertext_len, const unsigned char key[16], const unsigned char iv[16], unsigned char *plaintext) {
    if (!ciphertext || !key || !iv || !plaintext || ciphertext_len < 0) {
        return -1;
    }

    AES_KEY aes_key;

    // CFB decryption uses the encrypt key schedule.
    if (AES_set_encrypt_key(key, 128, &aes_key) != 0)
        return -2;
    

    // AES_cfb128_encrypt mutates the IV/state, so copy it if caller expects IV unchanged.
    unsigned char iv_local[16];
    memcpy(iv_local, iv, sizeof(iv_local));
    int num = 0;
    AES_cfb128_encrypt(ciphertext, plaintext, (size_t)ciphertext_len, &aes_key, iv_local, &num, AES_DECRYPT);

    return ciphertext_len;
}
int aes_cfb128_encrypt(const unsigned char *plaintext, int len, const unsigned char key[16], const unsigned char iv[16], unsigned char *ciphertext)
{
    AES_KEY aes_key;
    unsigned char iv_local[16];
    int num = 0;

    if (AES_set_encrypt_key(key, 128, &aes_key) != 0)
        return -1;

    memcpy(iv_local, iv, 16);

    AES_cfb128_encrypt(plaintext, ciphertext, len, &aes_key, iv_local, &num, AES_ENCRYPT);

    return len;
}
